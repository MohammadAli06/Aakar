/// Every state and union territory, in the order declared above.
final List<String> indiaStates = indiaLocations.keys.toList(growable: false);

/// The canonical state/union-territory name for [value], or null when the text
/// does not name one we carry.
String? canonicalState(String? value) {
  final query = value?.trim().toLowerCase() ?? '';
  if (query.isEmpty) return null;
  for (final state in indiaLocations.keys) {
    if (state.toLowerCase() == query) return state;
  }
  return null;
}

/// Cities and districts for [state]. Empty when the state is unknown, so the
/// city suggestions only appear once a state has been chosen.
List<String> citiesForState(String? state) {
  final canonical = canonicalState(state);
  return canonical == null ? const [] : indiaLocations[canonical]!;
}
